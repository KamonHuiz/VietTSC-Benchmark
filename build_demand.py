#!/usr/bin/env python3
"""Build the benchmark scenarios: SUMO demand that reproduces the camera-measured flow.

Inputs
  results/flow/demand_settings.json   vehicles/hour per camera and class for light / medium / heavy
                                       (flow_estimation.window, from the real city cameras)
  sumo/config/camera_segments.json    which SUMO edges each camera observes

For every split (train / val / test) and every setting (light / medium / heavy):
  1. candidate routes: every fringe-to-fringe route per vehicle class (randomTrips --fringe-factor max routed by
     duarouter: shortest path that respects turn bans and vClass permissions; computed once, deterministic);
  2. targets: count of each camera / 2 per direction x --scale, on each observed edge, for [0, 3600) s;
  3. SUMO routeSampler draws routes at random until every observed edge reaches its target; departures are
     uniform in [0, 3600). The split's FIXED seed drives the draw, so the three splits share the same flow
     per observed edge but differ in routes and departure times.
Bicycles are not observed by the cameras: every scenario reuses the original random bicycle trips.

    python build_demand.py                      # all splits, all settings, scale 0.25 (benchmark default)
    python build_demand.py --split test --mode heavy
    python build_demand.py --scale 1.0 --tag full   # 100 % of camera flow (oversaturates the network)
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
NET = ROOT / "sumo/map/hcmc.net.xml.gz"
SETTINGS = ROOT / "results/flow/demand_settings.json"
SEGMENTS = ROOT / "sumo/config/camera_segments.json"
CACHE = ROOT / "sumo/demand_cache"

SPLIT_SEEDS = {"train": 1001, "val": 2002, "test": 3003}      # FIXED: the benchmark is defined by these
MODES = ("light", "medium", "heavy")
DEFAULT_SCALE = 0.25    # largest scale where heavy still flows on this network (0.3+ queues at the entries)

CLASSES = {  # vClass -> (camera class, file stem, vType id, id prefix)
    "motorcycle": ("motorcycle", "motorcycle", "motorcycle_motorcycle", "motorcycle"),
    "passenger": ("car", "passenger", "veh_passenger", "veh"),
    "truck": ("truck", "truck", "truck_truck", "truck"),
    "bus": ("bus", "bus", "bus_bus", "bus"),
}
VTYPE = {
    "motorcycle": ('<vType id="motorcycle_motorcycle" vClass="motorcycle" length="1.9" width="0.7" minGap="0.5" '
                   'minGapLat="0.3" maxSpeed="13.9" accel="2.5" decel="5.0" sigma="0.5" tau="1.0" '
                   'latAlignment="arbitrary" maxSpeedLat="1.5" lcSublane="5" lcPushy="0.6" lcAssertive="1.5"/>'),
    "passenger": '<vType id="veh_passenger" vClass="passenger"/>',
    "truck": '<vType id="truck_truck" vClass="truck"/>',
    "bus": '<vType id="bus_bus" vClass="bus"/>',
}
SUMOCFG = """<?xml version="1.0" encoding="UTF-8"?>
<!-- VietTSC-Benchmark scenario: split={split} setting={mode} seed={seed} scale={scale}. Generated by build_demand.py -->
<sumoConfiguration xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="http://sumo.dlr.de/xsd/sumoConfiguration.xsd">
    <input>
        <net-file value="../../../map/hcmc.net.xml.gz"/>
        <route-files value="osm.bicycle.trips.xml,osm.bus.trips.xml,osm.motorcycle.trips.xml,osm.passenger.trips.xml,osm.truck.trips.xml"/>
        <additional-files value="../../../map/osm.poly.xml.gz,../../../config/output.add.xml"/>
    </input>
    <output>
        <tripinfo-output value="tripinfos.xml"/>
        <statistic-output value="stats.xml"/>
    </output>
    <processing>
        <ignore-route-errors value="true"/>
        <!-- sublane model: motorcycles ride side by side and filter between cars -->
        <lateral-resolution value="0.4"/>
        <time-to-teleport value="300"/>
        <!-- count only physical overlap as a collision (sublane motorcycles ride close) -->
        <collision.mingap-factor value="0"/>
    </processing>
    <report>
        <verbose value="true"/>
        <duration-log.statistics value="true"/>
        <no-step-log value="true"/>
    </report>
    <gui_only>
        <gui-settings-file value="../../../config/osm.view.xml"/>
    </gui_only>
</sumoConfiguration>
"""


def tools() -> Path:
    home = os.environ.get("SUMO_HOME")
    if not home:
        try:
            import sumo
            home = sumo.SUMO_HOME
        except ImportError:
            sys.exit("SUMO_HOME is not set (and the eclipse-sumo pip package is not installed).")
    return Path(home) / "tools"


def run(cmd):
    print(">", " ".join(map(str, cmd)), flush=True)
    subprocess.run(list(map(str, cmd)), check=True, stdout=subprocess.DEVNULL)


def candidates(vclass: str) -> Path:
    CACHE.mkdir(parents=True, exist_ok=True)
    out = CACHE / f"cand.{vclass}.rou.xml"
    if not out.is_file():
        run([sys.executable, tools() / "randomTrips.py", "-n", NET, "--fringe-factor", "max", "-p", "0.1",
             "-b", "0", "-e", "3600", "--vehicle-class", vclass, "--vclass", vclass, "--prefix", f"c{vclass}",
             "--seed", "1", "--validate", "--remove-loops", "-o", CACHE / f"cand.{vclass}.trips.xml", "-r", out])
    return out


def counts_file(setting: dict, cam_class: str, scale: float, path: Path) -> Path:
    seg = json.load(open(SEGMENTS, encoding="utf-8"))
    rows = []
    for cam, spec in seg.items():
        if cam.startswith("_"):
            continue
        half = setting["cameras"][cam][cam_class] / 2 * scale
        for edges in spec["directions"]:
            rows += [f'        <edge id="{e}" entered="{half:.0f}"/>' for e in edges]
    path.write_text('<data>\n    <interval id="cam" begin="0" end="3600">\n' + "\n".join(rows) + "\n    </interval>\n</data>\n")
    return path


def build(split: str, mode: str, scale: float, root: Path):
    seed = SPLIT_SEEDS[split]
    settings = json.load(open(SETTINGS, encoding="utf-8"))
    out = root / split / mode
    out.mkdir(parents=True, exist_ok=True)
    targets = {}
    for vclass, (cam_class, stem, vtype, prefix) in CLASSES.items():
        cnt = counts_file(settings[mode], cam_class, scale, out / f"counts.{stem}.xml")
        tmp = CACHE / f"sampled.{split}.{mode}.{vclass}.rou.xml"
        run([sys.executable, tools() / "routeSampler.py", "-r", candidates(vclass), "-d", cnt, "-o", tmp,
             "--prefix", f"{prefix}_", "-a", f'type="{vtype}" departLane="best" departSpeed="max"',
             "--seed", str(seed), "-b", "0", "-e", "3600"])
        txt = re.sub(r"<!-- generated on .*?-->\s*", "", tmp.read_text(), count=1, flags=re.S)   # drop timestamp
        cut = txt.index(">", txt.index("<routes")) + 1
        (out / f"osm.{stem}.trips.xml").write_text(txt[:cut] + "\n    " + VTYPE[vclass] + txt[cut:])
        targets[stem] = txt.count("<vehicle ")
    shutil.copy2(ROOT / "sumo/bicycle" / f"{mode}.bicycle.trips.xml", out / "osm.bicycle.trips.xml")
    (out / "osm.sumocfg").write_text(SUMOCFG.format(split=split, mode=mode, seed=seed, scale=scale))
    meta = {"split": split, "setting": mode, "seed": seed, "scale": scale,
            "source_window": {k: settings[mode][k] for k in ("session", "from", "to")},
            "vehicles": targets}
    json.dump(meta, open(out / "scenario.json", "w"), indent=1)
    print(f"[{split}/{mode}] seed {seed}: {targets}", flush=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--split", choices=list(SPLIT_SEEDS), help="default: all")
    ap.add_argument("--mode", choices=MODES, help="default: all")
    ap.add_argument("--scale", type=float, default=DEFAULT_SCALE)
    ap.add_argument("--tag", default="", help="write to sumo/scenarios_<tag>/ instead of sumo/scenarios/")
    a = ap.parse_args()
    root = ROOT / "sumo" / (f"scenarios_{a.tag}" if a.tag else "scenarios")
    for s in ([a.split] if a.split else list(SPLIT_SEEDS)):
        for m in ([a.mode] if a.mode else MODES):
            build(s, m, a.scale, root)


if __name__ == "__main__":
    main()
